QString lang() { return g_lang; }

QString t(const QString &key) {
    for (const auto &e : kTable) {
        if (key == QLatin1String(e.key))
            return QString::fromUtf8(g_lang == "zh" ? e.zh : e.en);
    }
    return key;
}
